"""Generate research tables from the completed measurement files."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import pandas as pd


def table(headers, rows):
    return "\n".join(["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"] +
                     ["| " + " | ".join(map(str, row)) + " |" for row in rows])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parents[1]
    parser.add_argument("--input", type=Path, default=root / "results/benchmark")
    parser.add_argument("--update-report", action="store_true")
    args = parser.parse_args()
    run = json.loads((args.input / "run.json").read_text())
    if run["status"] != "complete" or run["is_smoke_run"]:
        parser.error("A completed definitive benchmark is required")
    aggregate = pd.read_csv(args.input / "aggregate_summary.csv").set_index("method")
    series = pd.read_csv(args.input / "series_summary.csv")
    methods = ["linear", "extra_trees", "analog_bridge", "analog_no_bridge", "analog_constant_scale", "analog_pooled_calibration"]
    names = ["Linear", "ExtraTrees", "AnalogBridge", "No endpoint bridge", "Constant scale", "Pooled calibration"]
    rows = []
    for method, name in zip(methods, names):
        r = aggregate.loc[method]
        rows.append([name, f"{r.normalized_mae:.4f}", f"{100*r.gap_coverage:.2f}%", f"{r.normalized_width:.3f}", f"{1000*r.prediction_seconds:.3f}"])
    macro = table(["Method", "MAE / training IQR ↓", "Whole-gap coverage", "Width / training IQR ↓", "Warm prediction ms/gap"], rows)
    rows = []
    for dataset in sorted(series.dataset.unique()):
        s = series[series.dataset == dataset].set_index("method")
        r = s.loc["analog_bridge"]
        rows.append([dataset, f"{s.loc['linear','mae']:.3f}", f"{s.loc['extra_trees','mae']:.3f}", f"{r.mae:.3f}", f"{100*r.gap_coverage:.2f}%", f"{r.mean_width:.3f}"])
    by_series = table(["Series", "Linear MAE", "ExtraTrees MAE", "AnalogBridge MAE", "Analog gap coverage", "Analog mean band width"], rows)
    a = aggregate.loc["analog_bridge"]
    text = (f"<!-- Generated by scripts/summarize_results.py; run {run['run_id']} -->\n\n"
            "Equal weight is assigned to each series, seed and gap length. Raw per-series errors are in source units; do not average those units. Nominal whole-gap coverage is 90%.\n\n" + macro + "\n\n" + by_series + "\n\n"
            f"AnalogBridge mask-seed range: normalized MAE {a.normalized_mae_seed_min:.4f}–{a.normalized_mae_seed_max:.4f}; gap coverage {100*a.gap_coverage_seed_min:.2f}%–{100*a.gap_coverage_seed_max:.2f}%. These are sensitivity ranges, not confidence intervals.\n")
    (args.input / "tables.md").write_text(text, encoding="utf-8")
    provenance = {"run_id": run["run_id"], "source_sha256": {
        n: hashlib.sha256((args.input / n).read_bytes()).hexdigest()
        for n in ["run.json", "aggregate_summary.csv", "series_summary.csv"]}}
    (args.input / "tables_provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    if args.update_report:
        report = root / "docs/RESEARCH_REPORT.md"
        original = report.read_text(encoding="utf-8")
        start, end = "<!-- BEGIN GENERATED TABLES -->", "<!-- END GENERATED TABLES -->"
        if original.count(start) != 1 or original.count(end) != 1:
            parser.error("Research report must contain exactly one table marker pair")
        before, rest = original.split(start)
        _, after = rest.split(end)
        report.write_text(before + start + "\n\n" + text + "\n" + end + after, encoding="utf-8")
    print("Generated tables.md and tables_provenance.json" + ("; research report refreshed" if args.update_report else ""))


if __name__ == "__main__":
    main()
